let currentLang = 'ko';

function toggleLanguage() {
    currentLang = currentLang === 'ko' ? 'en' : 'ko';
    updateContent();
    document.querySelector('.lang-switch').innerText = currentLang === 'ko' ? 'EN' : 'KO';
}

function updateContent() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (translations[currentLang][key]) {
            el.innerHTML = translations[currentLang][key];
        }
    });

    // Update placeholders
    const inputs = {
        nationality: currentLang === 'ko' ? "예: 대한민국" : "e.g. United Kingdom",
        name: currentLang === 'ko' ? "이름을 입력하세요" : "Enter your name",
        email: currentLang === 'ko' ? "example@email.com" : "example@email.com"
    };

    document.querySelector('input[name="nationality"]').placeholder = inputs.nationality;
    document.querySelector('input[name="name"]').placeholder = inputs.name;
    document.querySelector('input[name="email"]').placeholder = inputs.email;
}

// Step Form Logic
function nextStep(step) {
    document.querySelectorAll('.step').forEach(s => s.classList.remove('active'));
    document.getElementById('step' + step).classList.add('active');
}

// Accordion Logic
function toggleAccordion(header) {
    const content = header.nextElementSibling;
    const isActive = content.classList.contains('active');
    
    // Close all
    document.querySelectorAll('.accordion-content').forEach(c => c.classList.remove('active'));
    
    if (!isActive) {
        content.classList.add('active');
    }
}

